interface ManifesteCommitmentsProps {
  data?: any;
}

const ManifesteCommitments: React.FC<ManifesteCommitmentsProps> = ({
  data,
}) => {
  const titleRef = useRef<HTMLHeadingElement>(null);

  useEffect(() => {
    gsap.registerPlugin(ScrollTrigger);

    const ctx = gsap.context(() => {
      if (titleRef.current) {
        const animatables = titleRef.current.querySelectorAll(
          `.${styles.word}, .${styles.icon}`
        );

        const tl = gsap.timeline({
          scrollTrigger: {
            trigger: titleRef.current,
            start: "top 80%",
            end: "bottom 60%",
            scrub: true,
          },
        });

        const state = { count: 0 };

        tl.to(state, {
          count: animatables.length,
          ease: "none",
          duration: 1,
          onUpdate: () => {
            const activeCount = Math.ceil(state.count);
            animatables.forEach((el, i) => {
              const hasActive = el.classList.contains(styles.active);
              if (i < activeCount) {
                if (!hasActive) el.classList.add(styles.active);
              } else {
                if (hasActive) el.classList.remove(styles.active);
              }
            });
          },
        });
      }
    });

    return () => ctx.revert();
  }, [data]);

  const renderWords = (text: string) => {
    return text
      .split(" ")
      .filter((word) => word !== "")
      .map((word, index) => (
        <span key={index} className={styles.word}>
          {word}{" "}
        </span>
      ));
  };

  // Parser pour extraire les SVG du texte Strapi
  const renderTitleContent = () => {
    const fullText =
      data?.Texte?.map((p: any) =>
        p.children?.map((c: any) => c.text).join("")
      ).join("") || "";

    // Regex pour isoler les balises SVG
    const parts = fullText.split(/(<svg[\s\S]*?<\/svg>)/g);

    return parts.map((part: string, index: number) => {
      if (part.startsWith("<svg")) {
        return (
          <div
            key={index}
            className={styles.icon}
            dangerouslySetInnerHTML={{ __html: part }}
          />
        );
      } else {
        return <React.Fragment key={index}>{renderWords(part)}</React.Fragment>;
      }
    });
  };

  return (
    <section className={`${styles.manifesteCommitments} pt-top pb-bottom`}>
      <div className="container">
        <div className={styles.header}>
          <span className="label">{data?.Label || "ENTREPRISE À MISSION"}</span>
          <div className={styles.statement}>
            <h2 ref={titleRef}>{renderTitleContent()}</h2>
          </div>
        </div>

        <div className={styles.commitGrid}>
          {data?.Item?.map((val: any, index: number) => (
            <div key={val.id || index} className={styles.commitItem}>
              <div className={styles.itemHeader}>
                <span className={styles.itemIcon}>
                  {hardcodedIcons[index % hardcodedIcons.length]}
                </span>
                <h3 className={styles.itemTitle}>{val.Titre}</h3>
              </div>
              <div className={styles.itemContent}>
                {val.Description?.map((p: any, pIdx: number) => (
                  <p key={pIdx}>
                    {p.children?.map((c: any) => c.text).join("")}
                  </p>
                ))}
              </div>
            </div>
          ))}
        </div>
      </div>
    </section>
  );
};

export default ManifesteCommitments;
